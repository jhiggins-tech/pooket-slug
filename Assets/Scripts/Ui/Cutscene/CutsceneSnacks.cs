        /// <summary>The splat's frames, in <see cref="SnackShow.SplatFrame"/>'s order, each 24 x 32 from the feet.</summary>
        public static Sprite[] Splat
        {
            get
            {
                if (s_Splat != null) return s_Splat;
                s_Splat = new Sprite[SplatRows.Length];
                for (int i = 0; i < SplatRows.Length; i++)
                {
                    var c = new PixelCanvas(24, 32);
                    c.Ascii(SplatRows[i], SoftPal, 0, 0);
                    s_Splat[i] = Art.ToSprite(c, new Vector2(0.5f, 0f));
                }
                return s_Splat;
            }
        }

        static Sprite Make(string[] rows, Dictionary<char, Color32> pal = null, Vector2? pivot = null)
        {
            var c = new PixelCanvas(rows[0].Length, rows.Length);
            c.Ascii(rows, pal ?? Pal, 0, 0);
            return Art.ToSprite(c, pivot ?? new Vector2(0.5f, 0f));
        }
    }
